// Generates a browser-compatible copy of the graded library WITHOUT editing the original.
// Run automatically before dev/build:  node scripts/sync-crypto.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SRC = process.env.PM_SRC || resolve(here, "../../cryptography/password-manager.js");
const OUT = resolve(here, "../src/crypto/password-manager.generated.js");

let code = readFileSync(SRC, "utf8");

const requireLib = /const \{[^}]*\} = require\("\.\/lib"\);/;
const requireSubtle = /const \{ subtle \} = require\('crypto'\)\.webcrypto;/;
const exportsLine = /module\.exports = \{ Keychain \}/;

for (const [name, re] of [["require(./lib)", requireLib], ["require(crypto)", requireSubtle], ["module.exports", exportsLine]]) {
  if (!re.test(code)) throw new Error(`sync-crypto: could not find ${name} in ${SRC}`);
}

code = code
  .replace(requireLib, 'import { stringToBuffer, bufferToString, encodeBuffer, decodeBuffer, getRandomBytes } from "./browser-lib.js";')
  .replace(requireSubtle, "const subtle = globalThis.crypto.subtle;")
  .replace(exportsLine, "export { Keychain };");

const banner = "// AUTO-GENERATED by scripts/sync-crypto.mjs from cryptography/password-manager.js. DO NOT EDIT.\n";
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, banner + code);
console.log("Generated", OUT);